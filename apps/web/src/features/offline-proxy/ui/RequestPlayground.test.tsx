import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { RequestPlayground } from './RequestPlayground.tsx'

function stubFetch(response: Response | Error) {
  const fetchMock = vi.fn(async () => {
    if (response instanceof Error) throw response
    return response
  })
  vi.stubGlobal('fetch', fetchMock)
  return fetchMock
}

async function clickSend(index: number) {
  const buttons = screen.getAllByRole('button', { name: '送信' })
  const button = buttons[index]
  if (!button) throw new Error(`send button #${index} should exist`)
  await userEvent.setup().click(button)
}

describe('RequestPlayground', () => {
  it('labels responses generated by the service worker and notifies the parent', async () => {
    const fetchMock = stubFetch(
      new Response(JSON.stringify({ fortune: '大吉' }), {
        status: 200,
        headers: { 'Content-Type': 'application/json', 'X-Served-By': 'sw-mock' },
      }),
    )
    const onSettled = vi.fn()
    render(<RequestPlayground controlled onSettled={onSettled} />)

    await clickSend(0)

    expect(await screen.findByText(/その場で生成/)).toBeInTheDocument()
    expect(screen.getByText(/"fortune": "大吉"/)).toBeInTheDocument()
    expect(fetchMock).toHaveBeenCalledWith(
      '/sw-api/fortune',
      expect.objectContaining({ cache: 'no-store', headers: { Accept: 'application/json' } }),
    )
    expect(onSettled).toHaveBeenCalledTimes(1)
  })

  it('shows cache fallbacks together with the original Date header', async () => {
    stubFetch(
      new Response('{}', {
        status: 200,
        headers: { 'X-Served-By': 'sw-cache', Date: 'Fri, 16 Oct 2026 00:00:00 GMT' },
      }),
    )
    render(<RequestPlayground controlled />)

    await clickSend(1)

    expect(await screen.findByText(/キャッシュから返した/)).toBeInTheDocument()
    expect(screen.getByText(/Fri, 16 Oct 2026 00:00:00 GMT/)).toBeInTheDocument()
  })

  it('explains that the request reached the server when no service worker controls the page', async () => {
    stubFetch(new Response('Not Found', { status: 404 }))
    render(<RequestPlayground controlled={false} />)

    await clickSend(0)

    expect(await screen.findByText('HTTP 404')).toBeInTheDocument()
    expect(screen.getByText(/Service Worker を通っていない/)).toBeInTheDocument()
  })

  it('reports network failures instead of failing silently', async () => {
    stubFetch(new TypeError('Failed to fetch'))
    render(<RequestPlayground controlled={false} />)

    await clickSend(1)

    expect(await screen.findByRole('alert')).toHaveTextContent('リクエストに失敗しました（Failed to fetch）')
  })
})
